def detect_race(*texts):
    """从多段文本（标题在前，优先）中识别分站名，返回「美国站」或「赛季整体」。"""
    text = " ".join(t for t in texts if t)
    if not text:
        return SEASON_WIDE
    m = _KW_RE.search(text)
    if m:
        return _MAP[m.group(1)]
    return SEASON_WIDE


def to_gp_name(race):
    """「迈阿密站」→「迈阿密大奖赛」，用于构造 B站搜索词。
    B站搜索对「XX站」拆词太松（返回热门站内容），「XX大奖赛」才是有效词。"""
    if race.endswith("站"):
        return race[:-1] + "大奖赛"
    return race
